// NetData.h
#pragma once
#include "objBase.h"

//-----------------------------------------------------
// 通信するプレイヤーデータ
//-----------------------------------------------------
struct PlayerSendData {
    //プレイヤー座標
    Point pos;
    //向き
    int dir;
    //攻撃カウンタ
    int attackCount{ 0 };
    bool alive{ false };

};

//-----------------------------------------------------
// プレイヤーデータ
//-----------------------------------------------------
struct PlayerData {
    //プレイヤーのID
    int PlayerID{ -1 };
    //位置情報
    Point pos{ 0,0 };
    //接続状態
    NetState netState{ NetState::CONNECTED };
    //向き
    int dir{ (int)DIR::DOWN };
    //攻撃カウンタ
    int attackCount{ 0 };
    int exp{ 0 };
    bool alive{ true };
};

//-----------------------------------------------------
// 接続時にプレイヤーIDを通知するデータ
//-----------------------------------------------------
struct CJoinData {
    int PlayerID;
};

//-----------------------------------------------------
// 敵データ
//-----------------------------------------------------
struct EnemyData {
    //敵のID
    int enemyID{ -1 };
    //位置
    Point pos{ 0,0 };
};

//-----------------------------------------------------
// アイテムデータ
//-----------------------------------------------------
struct ItemData {
    //アイテムのID
    int itemID{ -1 };
    //位置
    Point pos{ 0,0 };
};

//-----------------------------------------------------
// サーバから送信するデータ
//-----------------------------------------------------
struct CNetDataAll {
    //プレイヤー情報
    PlayerData player[MAX_PLAYER];
    //敵情報
    EnemyData enemy[MAX_ENEMY];
    //アイテム情報
    ItemData item[MAX_ITEM];
};
